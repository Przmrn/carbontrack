export type EnCopy = typeof en;

// Widened copy type: same shape as `en`, but strings are plain strings and
// arrays are readonly, so another language can satisfy the same keys.
export type DeepWiden<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends readonly (infer U)[]
      ? readonly DeepWiden<U>[]
      : T extends object
        ? { [K in keyof T]: DeepWiden<T[K]> }
        : T;

export type Copy = DeepWiden<EnCopy>;
